/** 在目标文档上建出快车道行（一次性注入样式）。纯 DOM，React 仓经 ref 回调挂载。 */
export function mountStarRow(doc?: Document): HTMLElement {
  const d = doc ?? document;
  if (!d.getElementById(STYLE_ID)) {
    const tag = d.createElement("style");
    tag.id = STYLE_ID;
    tag.textContent = STYLE_CSS;
    d.head.appendChild(tag);
  }
  const match = REPO_URL.match(/github\.com\/([^/]+\/[^/#?]+)/);
  const repo = match ? match[1]! : "drscrewdriver";
  const a = d.createElement("a");
  a.className = "dsh-star-row";
  a.href = REPO_URL;
  a.target = "_blank";
  a.rel = "noreferrer";
  a.dataset.starNs = STAR_NS;

  const svg = d.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("aria-hidden", "true");
  const path = d.createElementNS("http://www.w3.org/2000/svg", "path");
  path.setAttribute("fill", "currentColor");
  path.setAttribute("d", GITHUB_MARK_PATH);
  svg.appendChild(path);
  a.appendChild(svg);

  const label = d.createElement("span");
  label.textContent = repo;
  a.appendChild(label);
  // STAR:EXTENDED:BEGIN — S 档在此接管（A/L 副本由 sync 剥除本段）
  const row = extendedStarRow(a, d);
  if (row) return row;
  // STAR:EXTENDED:END

  if (STAR_VARIANT === "A") {
    const ask = d.createElement("span");
    ask.className = "dsh-star-ask";
    ask.textContent = pickLang().ask;
    a.appendChild(ask);
  }
  // L 档：仅中性仓库链接，无话术。S 档细条在后续批次扩展。
  return a;
}
