/** 宿主语言标签归一：取 `documentElement.lang` 的前缀，命中 STAR_LANGS 即用。 */
function starLang(): string {
  const tag = (typeof document !== "undefined" && document.documentElement.lang) || "";
  const low = tag.toLowerCase();
  for (const cand of STAR_LANGS) if (low.startsWith(cand)) return cand;
  return "en";
}

/** 是否已被用户点掉话术（隐私模式下读失败按未关闭处理，只影响本次会话）。 */
function starDismissed(): boolean {
  try {
    return localStorage.getItem("dsh.star." + STAR_NS + ".dismissed") === "1";
  } catch {
    return false;
  }
}

/** 记住关闭态（隐私模式写失败不报错，话术本次隐藏、刷新复活）。 */
function starDismiss(): void {
  try {
    localStorage.setItem("dsh.star." + STAR_NS + ".dismissed", "1");
  } catch {
    /* noop */
  }
}

/** 一次性注入 S 档样式。 */
function injectStarSStyle(d: Document): void {
  if (d.getElementById(STAR_S_STYLE_ID)) return;
  const style = d.createElement("style");
  style.id = STAR_S_STYLE_ID;
  style.textContent = STAR_S_STYLE;
  d.head.appendChild(style);
}

/** 打开仓库页：桌面壳里 window.open 可能被拦，锚点 click 才是两条路径都通的写法。 */
function openRepo(d: Document): void {
  const a = d.createElement("a");
  a.href = REPO_URL;
  a.target = "_blank";
  a.rel = "noopener noreferrer";
  a.click();
}

/** S 档扩充：把裸链接行升级成「链接 ｜ 话术 ｜ ★ CTA ｜ × 隐藏」，非 S 档返回 null 走原路径。 */
function extendedStarRow(link: HTMLElement, d: Document): HTMLElement | null {
  if (STAR_VARIANT !== "S") return null;
  if (starDismissed()) return link;
  injectStarSStyle(d);
  link.className = "dsh-star-link";
  const lang = starLang();
  const row = d.createElement("div");
  row.className = "dsh-star-row-s";
  row.appendChild(link);
  const ask = d.createElement("span");
  ask.className = "dsh-star-ask";
  ask.textContent = STAR_COPY[lang]!.ask;
  row.appendChild(ask);
  const cta = d.createElement("button");
  cta.type = "button";
  cta.className = "dsh-star-cta";
  cta.textContent = "★ " + STAR_CTA[lang];
  cta.addEventListener("click", (event: Event) => {
    // 行内的 ★ 是「去点星」：打开仓库页，不隐藏。
    event.preventDefault();
    event.stopPropagation();
    openRepo(d);
  });
  row.appendChild(cta);
  const hide = d.createElement("button");
  hide.type = "button";
  hide.className = "dsh-star-hide";
  hide.textContent = "×";
  hide.title = STAR_HIDE[lang]!;
  hide.setAttribute("aria-label", STAR_HIDE[lang]!);
  hide.addEventListener("click", (event: Event) => {
    // 隐藏才是「别打扰我」：收话术与两钮，链接段永留。
    event.preventDefault();
    event.stopPropagation();
    starDismiss();
    if (row.parentNode) {
      row.parentNode.replaceChild(link, row);
      link.className = "dsh-star-row";
    }
  });
  row.appendChild(hide);
  return row;
}
